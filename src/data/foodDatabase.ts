import type { FoodItem, HealthScore } from "@/types/health";

function genFoodId(name: string): string {
  return `food-${name.replace(/\s+/g, "-")}`;
}

const now = Date.now();

function food(
  name: string,
  category: string,
  cal: number,
  c: number,
  p: number,
  f: number,
  score: HealthScore,
  units: { name: string; grams: number }[],
  extras: Partial<FoodItem> = {},
): FoodItem {
  return {
    id: genFoodId(name),
    name,
    category,
    caloriesPer100g: cal,
    carbsPer100g: c,
    proteinPer100g: p,
    fatPer100g: f,
    healthScore: score,
    units,
    custom: false,
    createdAt: now,
    updatedAt: now,
    ...extras,
  };
}

