/** 组装一个视图：底图体块（不描边）→ 剪影外轮廓描边 → 肌群分区 → 细节线 */
function buildSvg({title, axis, centerParts, sideParts, outline, extra = [], zOrder, regions, detail = [], mirrored = true}) {
  const dx = -axis + 330
  const shift = (pts) => pts.map(([x, y]) => [x + dx, y])
  const flip = (pts) => pts.map(([x, y]) => [2 * axis - x, y])
  const mirror = (pts) => rev(flip(pts))
  const both = (shape) => (mirrored ? [shape, mirror(shape)] : [shape])
  const sym = (half) => (mirrored ? [...half, ...mirror(half.slice(1, -1))] : half)
  let svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEWBOX}">`
  svg += `<title>${title}</title>`
  svg += `<g id="base">`
  for (const part of [...(centerParts || []).map(sym), ...(sideParts || []).flatMap((p) => both(p))]) {
    svg += `<path d="${toPath(shift(part))}"/>`
  }
  svg += `<path d="${toPath(shift(sym(outline)))}"/>`
  for (const s of extra.garment || []) svg += `<path class="garment" d="${toPath(shift(sym(s)))}"/>`
  for (const s of extra.hair || []) svg += `<path class="hair" d="${toPath(shift(sym(s)))}"/>`
  if (detail.length) {
    // 细节线（腹直肌腱划）只描边、不参与高亮，归入底图
    for (const d of detail) svg += `<path class="detail" d="${d}" style="fill:none"/>`
  }
  svg += `</g>`
  for (const key of zOrder) {
    const shapes = regions[key]
    if (!shapes) throw new Error(`missing region: ${key}`)
    svg += `<g class="m" data-m="${key}">`
    for (const shape of shapes) {
      for (const s of both(shape)) svg += `<path d="${toPath(shift(s))}"/>`
    }
    svg += `</g>`
  }
  svg += `</svg>`
  return svg
}

