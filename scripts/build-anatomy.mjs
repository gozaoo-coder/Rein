/** 经过控制点的路径。
 *  肌群分区之间共享边界点，必须逐点重合 —— 因此默认 tension 0（精确折线，
 *  控制点已按 20px 间隔实测，目标尺寸下不会显得棱角）。 */
function toPath(points, {closed = true, tension = 0} = {}) {
  const pts = closed ? [...points, points[0]] : [...points]
  if (pts.length < 2) return ''
  const at = (i) => pts[Math.max(0, Math.min(pts.length - 1, i))]
  let d = `M${r1(pts[0][0])} ${r1(pts[0][1])}`
  for (let i = 0; i < pts.length - 1; i += 1) {
    const p0 = at(i - 1)
    const p1 = at(i)
    const p2 = at(i + 1)
    const p3 = at(i + 2)
    const c1x = p1[0] + ((p2[0] - p0[0]) / 6) * tension
    const c1y = p1[1] + ((p2[1] - p0[1]) / 6) * tension
    const c2x = p2[0] - ((p3[0] - p1[0]) / 6) * tension
    const c2y = p2[1] - ((p3[1] - p1[1]) / 6) * tension
    d += `C${r1(c1x)} ${r1(c1y)} ${r1(c2x)} ${r1(c2y)} ${r1(p2[0])} ${r1(p2[1])}`
  }
  return closed ? `${d}Z` : d
}

const flip = (points) => points.map(([x, y]) => [2 * AXIS - x, y])
const rev = (points) => [...points].reverse()
/** 左半 → 左右两份（右侧顺序反转，保证闭合方向一致） */
const both = (shape) => [shape, rev(flip(shape))]
/** 首尾点落在中线上的左半 → 一条完整对称闭合形状 */
const sym = (half) => [...half, ...rev(flip(half.slice(1, -1)))]

